CREATE TABLE IF NOT EXISTS users(email TEXT PRIMARY KEY, created INTEGER);
CREATE TABLE IF NOT EXISTS codes(email TEXT PRIMARY KEY, hash TEXT, exp INTEGER, tries INTEGER DEFAULT 0, sent INTEGER);
CREATE TABLE IF NOT EXISTS sessions(hash TEXT PRIMARY KEY, email TEXT, exp INTEGER);
CREATE TABLE IF NOT EXISTS designs(id TEXT PRIMARY KEY, email TEXT, data TEXT, created INTEGER);
CREATE INDEX IF NOT EXISTS ix_designs_email ON designs(email);
CREATE TABLE IF NOT EXISTS orders(id TEXT PRIMARY KEY, email TEXT, data TEXT, total INTEGER, status TEXT, printify_id TEXT, tracking TEXT, created INTEGER, updated INTEGER);
CREATE INDEX IF NOT EXISTS ix_orders_email ON orders(email);
CREATE INDEX IF NOT EXISTS ix_orders_status ON orders(status);
CREATE TABLE IF NOT EXISTS subs(email TEXT PRIMARY KEY, created INTEGER);
CREATE TABLE IF NOT EXISTS msgs(id INTEGER PRIMARY KEY AUTOINCREMENT, email TEXT, body TEXT, created INTEGER);
CREATE TABLE IF NOT EXISTS oauth_states(state TEXT PRIMARY KEY, prov TEXT, next TEXT, exp INTEGER);
