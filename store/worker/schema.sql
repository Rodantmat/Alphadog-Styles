CREATE TABLE IF NOT EXISTS users(email TEXT PRIMARY KEY, created BIGINT);
CREATE TABLE IF NOT EXISTS codes(email TEXT PRIMARY KEY, hash TEXT, exp BIGINT, tries INTEGER DEFAULT 0, sent BIGINT);
CREATE TABLE IF NOT EXISTS sessions(hash TEXT PRIMARY KEY, email TEXT, exp BIGINT);
CREATE TABLE IF NOT EXISTS designs(id TEXT PRIMARY KEY, email TEXT, data TEXT, created BIGINT);
CREATE INDEX IF NOT EXISTS ix_designs_email ON designs(email);
CREATE TABLE IF NOT EXISTS orders(id TEXT PRIMARY KEY, email TEXT, data TEXT, total INTEGER, status TEXT, printify_id TEXT, tracking TEXT, created BIGINT, updated BIGINT);
CREATE INDEX IF NOT EXISTS ix_orders_email ON orders(email);
CREATE INDEX IF NOT EXISTS ix_orders_status ON orders(status);
CREATE TABLE IF NOT EXISTS subs(email TEXT PRIMARY KEY, created BIGINT);
CREATE TABLE IF NOT EXISTS msgs(id BIGSERIAL PRIMARY KEY, email TEXT, body TEXT, created BIGINT);
CREATE TABLE IF NOT EXISTS oauth_states(state TEXT PRIMARY KEY, prov TEXT, next TEXT, exp BIGINT);
CREATE TABLE IF NOT EXISTS custom_requests(id TEXT PRIMARY KEY, token TEXT, email TEXT, name TEXT, lang TEXT, data TEXT, status TEXT, quote INTEGER, note TEXT, created BIGINT, updated BIGINT);
CREATE INDEX IF NOT EXISTS ix_custom_status ON custom_requests(status);
CREATE TABLE IF NOT EXISTS custom_photos(id BIGSERIAL PRIMARY KEY, req_id TEXT, idx INTEGER, mime TEXT, b64 TEXT, created BIGINT);
CREATE INDEX IF NOT EXISTS ix_custom_photos_req ON custom_photos(req_id);
CREATE TABLE IF NOT EXISTS custom_art(req_id TEXT, part TEXT, mime TEXT, body TEXT, created BIGINT, PRIMARY KEY(req_id,part));
CREATE TABLE IF NOT EXISTS support_inbox(id BIGSERIAL PRIMARY KEY, mailbox TEXT, from_addr TEXT, subject TEXT, body TEXT, raw_size INTEGER, status TEXT DEFAULT 'new', created BIGINT, handled BIGINT, reply TEXT);
CREATE INDEX IF NOT EXISTS ix_support_status ON support_inbox(status);
CREATE TABLE IF NOT EXISTS kv(k TEXT PRIMARY KEY, v TEXT, updated BIGINT);
ALTER TABLE subs ADD COLUMN IF NOT EXISTS lang TEXT;
ALTER TABLE subs ADD COLUMN IF NOT EXISTS unsub BIGINT;
